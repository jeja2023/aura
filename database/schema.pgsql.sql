-- 寓瞳系统 PostgreSQL 基础表结构
-- 目标：PostgreSQL 16+，UTF-8

CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS sys_role (
  role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_name VARCHAR(64) NOT NULL,
  permission_json JSONB NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sys_user (
  user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_name VARCHAR(64) NOT NULL UNIQUE,
  display_name VARCHAR(64) NULL,
  password_hash VARCHAR(255) NOT NULL,
  role_id BIGINT NOT NULL REFERENCES sys_role(role_id),
  status SMALLINT NOT NULL DEFAULT 1,
  must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
  last_login_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS nvr_device (
  device_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(128) NOT NULL,
  ip VARCHAR(64) NOT NULL,
  port INT NOT NULL,
  brand VARCHAR(32) NOT NULL,
  protocol VARCHAR(32) NOT NULL,
  hmac_secret VARCHAR(255) NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'offline',
  last_seen_at TIMESTAMPTZ NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS map_roi (
  roi_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  camera_id BIGINT NOT NULL,
  room_node_id BIGINT NOT NULL,
  vertices_json JSONB NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS map_floor (
  floor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  node_id BIGINT NOT NULL,
  file_path VARCHAR(255) NOT NULL,
  scale_ratio NUMERIC(10,4) NOT NULL DEFAULT 1.0000,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS map_camera (
  camera_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  floor_id BIGINT NOT NULL,
  device_id BIGINT NOT NULL,
  channel_no INT NOT NULL,
  pos_x NUMERIC(12,4) NOT NULL DEFAULT 0,
  pos_y NUMERIC(12,4) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS dict_campus (
  node_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id BIGINT NULL,
  level_type VARCHAR(32) NOT NULL,
  node_name VARCHAR(128) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS capture_record (
  capture_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT NOT NULL,
  channel_no INT NOT NULL,
  capture_time TIMESTAMP NOT NULL,
  image_path TEXT NULL,
  feature_id VARCHAR(128) NULL,
  metadata_json JSONB NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS track_event (
  event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vid VARCHAR(64) NOT NULL,
  camera_id BIGINT NOT NULL,
  roi_id BIGINT NOT NULL,
  event_time TIMESTAMP NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS judge_result (
  judge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vid VARCHAR(64) NOT NULL,
  room_id BIGINT NOT NULL,
  judge_type VARCHAR(32) NOT NULL,
  judge_date DATE NOT NULL,
  detail_json JSONB NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS virtual_person (
  v_id VARCHAR(64) PRIMARY KEY,
  first_seen TIMESTAMP NOT NULL,
  last_seen TIMESTAMP NOT NULL,
  device_id BIGINT NOT NULL,
  capture_count INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS alert_record (
  alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alert_type VARCHAR(32) NOT NULL,
  vid VARCHAR(64) NULL,
  room_id BIGINT NULL,
  detail_json JSONB NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS log_operation (
  op_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operator_name VARCHAR(64) NOT NULL,
  action_type VARCHAR(64) NOT NULL,
  action_detail TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS log_system (
  system_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  level VARCHAR(16) NOT NULL,
  source VARCHAR(64) NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sys_config (
  config_key VARCHAR(128) PRIMARY KEY,
  config_value TEXT NOT NULL DEFAULT '',
  updated_by VARCHAR(64) NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS alert_workflow (
  workflow_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alert_id BIGINT NOT NULL REFERENCES alert_record(alert_id) ON DELETE CASCADE,
  status VARCHAR(32) NOT NULL DEFAULT 'open',
  assignee VARCHAR(64) NULL,
  priority VARCHAR(16) NOT NULL DEFAULT 'normal',
  escalation_level INT NOT NULL DEFAULT 0,
  handover_to VARCHAR(64) NULL,
  note TEXT NULL,
  closed_at TIMESTAMP NULL,
  updated_by VARCHAR(64) NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS space_topology_edge (
  edge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_camera_id BIGINT NOT NULL,
  to_camera_id BIGINT NOT NULL,
  relation_type VARCHAR(32) NOT NULL DEFAULT 'walkable',
  weight NUMERIC(10,4) NOT NULL DEFAULT 1.0000,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS space_heatmap_snapshot (
  snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  floor_id BIGINT NOT NULL,
  bucket_start TIMESTAMP NOT NULL,
  bucket_minutes INT NOT NULL DEFAULT 60,
  heat_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS report_schedule (
  schedule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_type VARCHAR(32) NOT NULL,
  cron_expr VARCHAR(64) NOT NULL,
  role_name VARCHAR(64) NOT NULL,
  delivery_channel VARCHAR(32) NOT NULL DEFAULT 'system',
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_by VARCHAR(64) NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS report_run (
  run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schedule_id BIGINT NULL REFERENCES report_schedule(schedule_id) ON DELETE SET NULL,
  report_type VARCHAR(32) NOT NULL,
  range_start DATE NOT NULL,
  range_end DATE NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'generated',
  summary_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_by VARCHAR(64) NULL,
  generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS report_delivery (
  delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL REFERENCES report_run(run_id) ON DELETE CASCADE,
  role_name VARCHAR(64) NOT NULL,
  delivery_channel VARCHAR(32) NOT NULL DEFAULT 'system',
  status VARCHAR(32) NOT NULL DEFAULT 'delivered',
  delivered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tenant_project (
  tenant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_code VARCHAR(64) NOT NULL UNIQUE,
  tenant_name VARCHAR(128) NOT NULL,
  config_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tenant_role_scope (
  scope_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL REFERENCES tenant_project(tenant_id) ON DELETE CASCADE,
  role_name VARCHAR(64) NOT NULL,
  permission_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ai_provider_config (
  provider_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_name VARCHAR(64) NOT NULL,
  provider_type VARCHAR(32) NOT NULL,
  endpoint_url TEXT NOT NULL,
  model_name VARCHAR(128) NOT NULL,
  model_version VARCHAR(64) NOT NULL DEFAULT 'default',
  traffic_weight INT NOT NULL DEFAULT 1,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ai_ab_experiment (
  experiment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  experiment_name VARCHAR(128) NOT NULL,
  provider_a_id BIGINT NOT NULL REFERENCES ai_provider_config(provider_id),
  provider_b_id BIGINT NOT NULL REFERENCES ai_provider_config(provider_id),
  traffic_split INT NOT NULL DEFAULT 50,
  metric_name VARCHAR(64) NOT NULL DEFAULT 'recall_at_k',
  enabled BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

