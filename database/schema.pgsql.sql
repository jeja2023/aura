  tenant_id BIGINT NOT NULL REFERENCES tenant_project(tenant_id) ON DELETE CASCADE,
  model_id BIGINT NOT NULL REFERENCES embedding_model(model_id) ON DELETE CASCADE,
  sample_count INT NOT NULL,
  top_k INT NOT NULL,
  recall_at_k NUMERIC(10,8) NULL,
  mrr NUMERIC(10,8) NULL,
  topk_overlap NUMERIC(10,8) NULL,
  empty_result_rate NUMERIC(10,8) NULL,
  pgvector_p95_ms NUMERIC(14,4) NULL,
  legacy_p95_ms NUMERIC(14,4) NULL,
  report_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_vector_shadow_sample CHECK(sample_count > 0 AND top_k > 0)
);
CREATE INDEX IF NOT EXISTS idx_vector_shadow_evaluation_model_time ON vector_shadow_evaluation(tenant_id,model_id,created_at DESC);
CREATE TABLE IF NOT EXISTS vector_write_compensation (
  compensation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  embedding_id BIGINT NOT NULL UNIQUE REFERENCES feature_embedding(embedding_id) ON DELETE CASCADE,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  attempt_count INT NOT NULL DEFAULT 0,
  available_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  locked_by VARCHAR(256) NULL,
  lock_until TIMESTAMPTZ NULL,
  last_error VARCHAR(2000) NULL,
  completed_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_vector_write_compensation_status CHECK(status IN ('pending','processing','retry_wait','completed','dead_letter')),
  CONSTRAINT ck_vector_write_compensation_attempt CHECK(attempt_count >= 0)
);
CREATE INDEX IF NOT EXISTS idx_vector_write_compensation_work ON vector_write_compensation(status,available_at,lock_until,compensation_id);
