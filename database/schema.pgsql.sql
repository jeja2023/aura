CREATE TABLE IF NOT EXISTS media_analysis_provider (
  provider_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NULL REFERENCES tenant_project(tenant_id) ON DELETE CASCADE,
  provider_code VARCHAR(64) NOT NULL,
  display_name VARCHAR(128) NOT NULL,
  adapter_type VARCHAR(64) NOT NULL DEFAULT 'standard_http',
  base_url TEXT NOT NULL,
  auth_type VARCHAR(32) NOT NULL DEFAULT 'hmac',
  secret_ref VARCHAR(255) NULL,
  webhook_auth_type VARCHAR(32) NOT NULL DEFAULT 'hmac',
  webhook_secret_ref VARCHAR(255) NULL,
  capabilities_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  protocol_version VARCHAR(32) NOT NULL DEFAULT '1.0',
  timeout_seconds INT NOT NULL DEFAULT 10 CHECK (timeout_seconds BETWEEN 1 AND 300),
  max_concurrency INT NOT NULL DEFAULT 16 CHECK (max_concurrency BETWEEN 1 AND 10000),
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_media_analysis_provider_auth CHECK (auth_type IN ('none', 'hmac', 'bearer', 'oauth2_client', 'mtls')),
  CONSTRAINT ck_media_analysis_provider_webhook_auth CHECK (webhook_auth_type IN ('hmac'))
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_media_analysis_provider_scope_code ON media_analysis_provider(COALESCE(tenant_id, 0), provider_code);
CREATE INDEX IF NOT EXISTS idx_media_analysis_provider_enabled ON media_analysis_provider(enabled, tenant_id, provider_id);

CREATE TABLE IF NOT EXISTS media_analysis_pipeline (
  pipeline_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id BIGINT NOT NULL REFERENCES media_analysis_provider(provider_id) ON DELETE CASCADE,
  pipeline_code VARCHAR(64) NOT NULL,
  display_name VARCHAR(128) NOT NULL,
  model_name VARCHAR(128) NOT NULL DEFAULT '',
  model_version VARCHAR(64) NOT NULL DEFAULT 'default',
