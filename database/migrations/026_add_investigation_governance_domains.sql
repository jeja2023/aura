-- Investigation, integration onboarding, data lifecycle, rule, AI and notification governance.

CREATE TABLE IF NOT EXISTS investigation_session (
  investigation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL REFERENCES tenant_project(tenant_id) ON DELETE RESTRICT,
  investigation_no VARCHAR(64) NOT NULL,
  title VARCHAR(256) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'active',
  owner_user_id BIGINT NULL REFERENCES sys_user(user_id) ON DELETE SET NULL,
  owner_name VARCHAR(128) NOT NULL,
  shared_with_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  version INT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ux_investigation_no UNIQUE(tenant_id,investigation_no),
  CONSTRAINT ck_investigation_status CHECK(status IN ('active','completed','archived'))
);

CREATE TABLE IF NOT EXISTS investigation_query_snapshot (
  query_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL REFERENCES tenant_project(tenant_id) ON DELETE RESTRICT,
  investigation_id BIGINT NOT NULL REFERENCES investigation_session(investigation_id) ON DELETE RESTRICT,
  query_type VARCHAR(32) NOT NULL,
  query_json JSONB NOT NULL,
  model_code VARCHAR(128) NULL,
  model_version VARCHAR(128) NULL,
  threshold_policy_version INT NULL,
  data_version VARCHAR(128) NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'queued',
