  created_by VARCHAR(128) NOT NULL,
  started_at TIMESTAMPTZ NULL,
  completed_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_investigation_query_status CHECK(status IN ('queued','running','partial','completed','failed','cancelled'))
);
CREATE INDEX IF NOT EXISTS idx_investigation_query_session ON investigation_query_snapshot(tenant_id,investigation_id,query_id DESC);

